/**
 * Converts Western digits 0-9 to Bengali digits ০-৯ if language is 'bn'
 */
export function formatNumber(value: number | string | null | undefined, lang: Language): string {
  if (value === null || value === undefined || value === "") return "";
  const str = typeof value === "number" ? value.toLocaleString("en-US") : String(value);
  if (lang !== "bn") return str;

  const bnDigits = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];
  return str.replace(/[0-9]/g, (d) => bnDigits[parseInt(d, 10)]);
}

/**
 * Formats currency amount in BDT (৳) according to the selected language
 */
export function formatCurrency(amount: number | null | undefined, lang: Language): string {
  if (amount === null || amount === undefined) return lang === "bn" ? "৳০" : "৳0";
  const formattedNum = formatNumber(Math.round(amount), lang);
  return `৳${formattedNum}`;
}

/**
 * Returns localized department name based on application language ('bn' or 'en')
 * Completely separates Bengali and English without mixed text.
 */
export function getDepartmentName(
  dept: { name?: string | null; nameBn?: string | null; nameEn?: string | null; departmentName?: string | null; departmentNameBn?: string | null; departmentNameEn?: string | null } | string | null | undefined,
  lang: Language = "bn"
): string {
  if (!dept) return "";
  if (typeof dept === "string") {
    if (lang === "bn") {
      const match = dept.match(/\(([\u0980-\u09FF\s&/.-]+)\)/);
      if (match) return match[1].trim();
      return dept.trim();
    } else {
      const beforeParen = dept.replace(/\(.*?\)/g, "").trim();
      return beforeParen || dept.trim();
    }
  }

  const bn = (dept.nameBn || dept.departmentNameBn || "").trim();
  const en = (dept.nameEn || dept.departmentNameEn || "").trim();
  const raw = (dept.name || dept.departmentName || "").trim();

  if (lang === "bn") {
    if (bn) return bn;
    if (raw) {
      const match = raw.match(/\(([\u0980-\u09FF\s&/.-]+)\)/);
      if (match) return match[1].trim();
      return raw;
    }
    return en;
  } else {
    if (en) return en;
    if (raw) {
      const beforeParen = raw.replace(/\(.*?\)/g, "").trim();
      return beforeParen || raw;
    }
    return bn;
  }
}

